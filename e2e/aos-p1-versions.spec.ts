// Academic OS P1-T3 against the REAL server (built web app, production server), phone 390 × 844 and desktop:
// Scenario 4 steps 2–3 without channels (PRD AOS-3.11, 3.12, 19H.2). The single owner has Lecture 5 (40 pages); they
// upload a renamed v2 («Abdomen lec5 final (1).pdf»: 2 pages inserted after p.10, p.30 rewritten) through the upload
// screen → the app proposes «إصدار جديد من …» (nothing applied) → the side-by-side compare marks the 2 inserted pages
// and the changed page → confirm → Lecture 5 has version 2. All files are labelled TEST FIXTURES
// (apps/server/test/fixtures/versions, generated by build.ts).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Page } from '@playwright/test';
import type { SourceDetail, SourceIdentityResponse, UploadResponse } from '@medlevo/shared';
import { CSRF_HEADERS, expect, screenshot, setupOwner, test } from './support';
import { REPO_ROOT } from './support/paths';

const FIXTURES = join(REPO_ROOT, 'apps', 'server', 'test', 'fixtures', 'versions');
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Structural accessibility probe (the repository has no axe-core): named controls, images with alt text, one h1,
 *  and 44 px touch targets for the controls of this track's screens. */
async function a11yProbe(page: Page): Promise<{ unnamed: string[]; imgNoAlt: number; h1: number; small: string[] }> {
  return page.evaluate(() => {
    const visible = (el: Element) => {
      const r = el.getBoundingClientRect();
      return r.width > 0 && r.height > 0 && getComputedStyle(el).visibility !== 'hidden';
    };
    const controls = Array.from(document.querySelectorAll('main button, main a[href], main input:not([type="hidden"]), main select')).filter(visible);
    const name = (el: Element) => (el.getAttribute('aria-label') ?? (el as HTMLElement).innerText ?? '').trim() || (el.querySelector('img[alt]')?.getAttribute('alt') ?? '').trim() || (el.id ? (document.querySelector(`label[for="${CSS.escape(el.id)}"]`)?.textContent ?? '').trim() : '');
    const unnamed = controls.filter((el) => !el.closest('[aria-hidden="true"], .ml-visually-hidden') && !name(el)).map((el) => el.outerHTML.slice(0, 80));
    // this track's controls only (the shared breadcrumbs are the design system's)
    const ours = Array.from(document.querySelectorAll('.ml-compare button, .ml-compare a[href], .ml-sugg button, .ml-sugg a[href], .ml-toc a[href]')).filter((el) => visible(el) && !el.closest('nav'));
    const small = ours.filter((el) => el.getBoundingClientRect().height < 43.5).map((el) => `${(el as HTMLElement).innerText.trim().slice(0, 30)} (${Math.round(el.getBoundingClientRect().height)}px)`);
    return { unnamed, imgNoAlt: Array.from(document.querySelectorAll('img')).filter((i) => visible(i) && !i.hasAttribute('alt')).length, h1: Array.from(document.querySelectorAll('h1')).filter(visible).length, small };
  });
}

test('P1-T3: a renamed new version is proposed, compared page by page and confirmed', async ({ page, api }, testInfo) => {
  test.setTimeout(300_000);
  await setupOwner(page);
  const { course } = await api.createNotebookAndCourse();
  const stamp = `${Date.now().toString(36)}-${testInfo.project.name}`;
  const title = `TEST FIXTURE Abdomen Lecture 5 ${stamp}`;

  // version 1 through the API, processed and analysed (its page fingerprints exist before v2 arrives)
  const res = await page.request.post('/api/sources/upload', {
    headers: { ...CSRF_HEADERS },
    multipart: { node_id: course.id, title, files: { name: 'Abdomen Lecture 5.pdf', mimeType: 'application/pdf', buffer: readFileSync(join(FIXTURES, 'scenario4-v1.pdf')) } },
  });
  expect(res.ok()).toBe(true);
  const v1 = (await res.json()) as UploadResponse;
  const lecture = v1.results[0]!;
  expect(lecture.status).toBe('accepted');
  await api.waitForProcessing(lecture.version_id!);
  for (let i = 0; ; i++) {
    const id = await api.get<SourceIdentityResponse>(`/api/versions/sources/${lecture.source_id}/identity`);
    if (id.analysis?.state === 'ready') {
      expect(id.identity).toMatchObject({ lecture_no: 5, lecture_no_origin: 'detected' });
      break;
    }
    if (i > 120) throw new Error(`analysis of version 1 did not finish: ${JSON.stringify(id.analysis)}`);
    await sleep(500);
  }

  // version 2: the owner uploads a renamed file through the upload screen
  await page.goto(`/upload?node=${course.id}`);
  await expect(page.getByRole('heading', { level: 1, name: 'رفع مصادر' })).toBeVisible();
  await page.locator('input[type="file"]').setInputFiles({ name: 'Abdomen lec5 final (1).pdf', mimeType: 'application/pdf', buffer: readFileSync(join(FIXTURES, 'scenario4-v2.pdf')) });
  await page.getByRole('button', { name: /^رفع ملف واحد/ }).click();
  const proposal = page.getByText(`إصدار جديد من «${title}»؟`);
  await expect(proposal).toBeVisible({ timeout: 180_000 });
  await expect(page.getByText(/تتطابق 39 من 40 صفحة/).first()).toBeVisible();
  // nothing applied yet: Lecture 5 still has one version
  expect((await api.source(lecture.source_id!)).versions).toHaveLength(1);
  await screenshot(page, testInfo, 'aos-p1-versions-proposal');

  // side-by-side compare: the 2 inserted pages and the rewritten page are marked
  await page.getByRole('link', { name: /قارن الصفحات قبل التأكيد/ }).first().click();
  await expect(page.getByRole('heading', { level: 1, name: 'مقارنة نسختين' })).toBeVisible();
  const rows = page.getByRole('list', { name: 'الصفحات' }).getByRole('listitem');
  await expect(rows).toHaveCount(42);
  await expect(page.locator('.ml-compare__row[data-change="inserted"]')).toHaveCount(2);
  await expect(page.locator('.ml-compare__row[data-change="changed"]')).toHaveCount(1);
  const changed = page.locator('.ml-compare__row[data-change="changed"]');
  await expect(changed.getByText('تحتاج تأكيدك')).toBeVisible();
  await expect(changed.getByText(/ص 30/).first()).toBeVisible();
  await expect(changed.getByText(/ص 32/).first()).toBeVisible();
  // the inserted pages sit right after p.10 of the new version
  const inserted = page.locator('.ml-compare__row[data-change="inserted"]');
  await expect(inserted.first().getByText('لا مقابل في النسخة السابقة')).toBeVisible();
  await expect(inserted.nth(0).getByText(/ص 11/).first()).toBeVisible();
  await expect(inserted.nth(1).getByText(/ص 12/).first()).toBeVisible();
  await expect(page.getByRole('status').filter({ hasText: 'صفحة جديدة: 2' })).toBeVisible();
  const probe = await a11yProbe(page);
  expect(probe.unnamed, 'unnamed controls').toEqual([]);
  expect(probe.imgNoAlt, 'images without alt').toBe(0);
  expect(probe.h1).toBe(1);
  // 44 px is the TOUCH target (the design system sizes controls for coarse pointers; a mouse gets the compact size)
  if (testInfo.project.name === 'phone') expect(probe.small, 'touch targets under 44 px').toEqual([]);
  await screenshot(page, testInfo, 'aos-p1-versions-compare');
  await page.emulateMedia({ colorScheme: 'dark' });
  await screenshot(page, testInfo, 'aos-p1-versions-compare-dark');
  await page.emulateMedia({ colorScheme: 'light' });

  // confirm → version 2 of Lecture 5 (the upload goes to the trash: nothing was written on it)
  await page.getByRole('button', { name: 'نعم، أضفه كإصدار جديد' }).click();
  await expect(page).toHaveURL(new RegExp(`/sources/${lecture.source_id}$`));
  await expect(page.getByRole('tab', { name: 'النسخ (2)' })).toBeVisible();
  const detail = await api.get<SourceDetail>(`/api/sources/${lecture.source_id}`);
  expect(detail.versions.map((v) => v.version_no).sort()).toEqual([1, 2]);
  await page.getByRole('tab', { name: 'النسخ (2)' }).click();
  await expect(page.getByRole('link', { name: 'قارن مع النسخة 1' })).toBeVisible();
  await screenshot(page, testInfo, 'aos-p1-versions-confirmed');

  // «المحاضرة»: the number found in the file (stored as detected), and the printed contents page as links (of the
  // version now studied — version 2, once processed)
  await api.waitForProcessing(detail.current_version_id!);
  await page.getByRole('tab', { name: 'المحاضرة' }).click();
  await expect(page.getByText('الرقم: اكتُشف تلقائيًا')).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'رقم المحاضرة', exact: true })).toHaveValue('5');
  await expect(page.getByRole('heading', { name: 'الفهرس المطبوع في الملف' })).toBeVisible({ timeout: 30_000 });
  const intro = page.getByRole('link', { name: /Introduction/ });
  await expect(intro).toHaveAttribute('href', new RegExp(`/study/${lecture.source_id}\\?v=.+&page=2$`));
  await screenshot(page, testInfo, 'aos-p1-versions-identity');
  await page.emulateMedia({ colorScheme: 'dark' });
  await screenshot(page, testInfo, 'aos-p1-versions-identity-dark');
});
