// G7 — AC-30 «الاستعادة»: a backup brings back sources, books, ink, questions, links and sessions VERIFIABLY; an archive
// without a tested restore is not enough.
//
// Adversarial additions to test/data/backup-restore.test.ts (which restores through the library functions and compares
// a list of key tables):
//  * the backup and the restore run through the REAL command-line tools as separate processes (`src/cli/backup.ts`
//    while the server is up, `src/cli/restore-verify.ts <archive> --target <dir>`), checking their exit codes and report;
//  * EVERY table of the database is compared row by row after the restore — not a chosen list — and the only allowed
//    differences are the ones a restore makes on purpose (sessions revoked, a new sync epoch, the restore entry in the
//    history, the CLI's own backup record), each asserted precisely;
//  * the owner's view is compared through the read APIs the web app uses (library, sources, pages, ink on lecture pages
//    AND on a separate note page, notes, the reading position, questions with their keys and lecture links, cards with
//    their review log and schedule, an exam in progress with its answers, a finished exam's result, the Study Book,
//    Arabic keyword search, reading progress) — the restored server must answer exactly the same.
// The Study Book is generated by the real job with the TEST-ONLY scripted provider (no API key exists here).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
